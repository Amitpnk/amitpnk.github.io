/*--------------------------------------------------------------
# Hero slideshow
# Shows every photo in assets/img/Slides/ automatically.
# Just add or delete photos in that folder and push; no code change needed.
#
# Photos are shown in file-name order (name them 01-..., 02-... to control it).
# To fine-tune which part of a photo stays in view, add it to POSITIONS
# (first value = left/right, second = top/bottom).
--------------------------------------------------------------*/
(function () {
  var FOLDER = 'assets/img/Slides/';
  var INTERVAL = 6000; // milliseconds per photo
  var DEFAULT_POSITION = 'center 30%';
  var POSITIONS = {
    // 'bike-2.jpg': '30% center',
  };
  var IMAGE = /\.(jpe?g|png|webp|avif|gif)$/i;

  var box = document.querySelector('#hero .hero-slides');
  if (!box) return;

  function getJSON(url) {
    return fetch(url, { cache: 'no-cache' }).then(function (r) {
      if (!r.ok) throw new Error(r.status);
      return r.json();
    });
  }

  // 1) Live site: list generated by GitHub Pages (slides.json)
  function fromManifest() {
    return getJSON('slides.json');
  }

  // 2) Local preview: read the folder listing from the dev server
  function fromFolderListing() {
    return fetch(FOLDER, { cache: 'no-cache' }).then(function (r) {
      if (!r.ok) throw new Error(r.status);
      return r.text();
    }).then(function (html) {
      var doc = new DOMParser().parseFromString(html, 'text/html');
      return Array.prototype.map.call(doc.querySelectorAll('a[href]'), function (a) {
        return FOLDER + decodeURIComponent(a.getAttribute('href').split('/').pop());
      });
    });
  }

  // 3) Fallback: ask GitHub for the folder contents
  function fromGitHub() {
    return getJSON('https://api.github.com/repos/Amitpnk/amitpnk.github.io/contents/' + FOLDER)
      .then(function (items) {
        return items.map(function (i) { return i.path; });
      });
  }

  function clean(list) {
    var seen = {};
    return (list || []).filter(function (p) {
      if (typeof p !== 'string' || !IMAGE.test(p) || seen[p]) return false;
      seen[p] = true;
      return true;
    }).sort(function (a, b) {
      return a.localeCompare(b, undefined, { numeric: true, sensitivity: 'base' });
    });
  }

  function attempt(fn) {
    return function (prev) {
      if (prev && prev.length) return prev;
      return fn().then(clean).catch(function () { return []; });
    };
  }

  Promise.resolve([])
    .then(attempt(fromManifest))
    .then(attempt(fromFolderListing))
    .then(attempt(fromGitHub))
    .then(build);

  function build(paths) {
    if (!paths.length) return;

    var slides = paths.map(function (p, i) {
      var name = p.split('/').pop();
      var div = document.createElement('div');
      div.className = 'hero-photo' + (i === 0 ? ' active' : '');
      div.style.backgroundImage = "url('" + encodeURI(p) + "')";
      div.style.backgroundPosition = POSITIONS[name] || DEFAULT_POSITION;
      box.appendChild(div);
      return div;
    });

    if (slides.length < 2) return;
    var i = 0;
    setInterval(function () {
      slides[i].classList.remove('active');
      i = (i + 1) % slides.length;
      slides[i].classList.add('active');
    }, INTERVAL);
  }
})();
